function reverse7(v:number){
	return ((v&1)<<6) |
	       ((v&2)<<4) |
	       ((v&4)<<2) |
	       ((v&8)>>0) |
	       ((v&16)>>2) |
	       ((v&32)>>4) |
	       ((v&64)>>6);
}



